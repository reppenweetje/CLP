//  - Sluitvraag in beide routes korter: "Wil je dat ik even met je meekijk
//    of dit wat voor je kan zijn?" / "Was [reden] voor jou de hoofdreden,
//    of speelden er nog andere dingen mee?".
//  - Sluitzin "Ik help je graag verder." geschrapt — voelt overbodig na
//    de uitnodigende vraag.
//  - Karakterlimiet verlaagd 700 → 500 zodat Gemini niet meer 4-alinea's
//    output produceert (code-laag in index.ts houdt 100-char safety
//    marge dus sanitize cap blijft 800).

export interface PromptInput {
  first_name?: string | null
  persona?: string | null
  intent_id?: string | null
  size_id?: string | null
  timeline_id?: string | null
  afhaak_reason?: string | null
  financing_interest?: boolean | null
  brochure_requested?: boolean | null
  email?: string | null
  project_name?: string | null
  project_city?: string | null
  attributes?: { rentRange?: string | null } | null
}

function fmt(value: unknown): string {
  if (value === null || value === undefined) return 'NULL'
  if (typeof value === 'string' && value.trim() === '') return 'NULL'
  if (typeof value === 'boolean') return value ? 'true' : 'false'
  return String(value)
}

